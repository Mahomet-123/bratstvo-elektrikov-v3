LINE_RE = re.compile(r"^\s*(\d{1,3})\s+(.+?)\s+(\S+)\s+(\d[\d ]*)\s*$")


def parse_text_items():
    out = {}
    with pdf_open(PDF) as pdf:
        for page in pdf.pages:
            txt = page.extract_text() or ""
            for line in txt.splitlines():
                m = LINE_RE.match(line.strip())
                if not m:
                    continue
                n = int(m.group(1))
                if n in out:
                    continue
                name = norm(m.group(2))
                unit = m.group(3)
                price = int(m.group(4).replace(" ", ""))
                out[n] = (name, unit, price, type_of(n))
    return out


def main():
    items = parse_text_items()

    for n, (name, unit, price, t) in FALLBACK.items():
        if n not in items:
            items[n] = (norm(name), unit, price, t)

    result = []
    for n in range(1, 207):
        if n not in items:
            print("  !! ПРОПУЩЕНА позиция", n)
            continue
        name, unit, price, t = items[n]
        sec = section_of(n)
        frm = (" от" in (" " + name)) or name.rstrip().endswith(" от")
        result.append({
            "section": sec,
            "n": n,
            "name": name,
            "unit": unit,
            "price": price,
            "from": bool(frm),
            "type": t,
        })

    result.sort(key=lambda x: x["n"])
    json.dump(result, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

